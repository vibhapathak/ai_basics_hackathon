const esc=s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
const clean=l=>l.replace(/^\s*\[?\d{1,2}:\d{2}(:\d{2})?\]?\s*[-–]?\s*/,'').trim();
const tpl=s=>s.replace(/[\w-]+\.\w{2,4}\b/g,'{file}').replace(/\b[A-Z]\d+(:[A-Z]\d+)?\b/g,'{range}').replace(/\d+/g,'{n}');

function detect(T){let best=null;const n=T.length;
  for(let s=0;s<n;s++)for(let p=1;s+2*p<=n;p++){let k=1;
    while(s+(k+1)*p<=n&&T.slice(s+k*p,s+(k+1)*p).every((t,i)=>t===T[s+i]))k++;
    if(k>=2){const sc=k*p;if(!best||sc>best.sc||(sc===best.sc&&p<best.p))best={s,p,k,sc}}}
  return best}

function build(text){
  const raw=text.split('\n').map(clean).filter(Boolean),T=raw.map(tpl),b=detect(T);
  if(!b)return{raw,k:0};
  const body=[...Array(b.p)].map((_,j)=>{const vals=[...Array(b.k)].map((_,r)=>raw[b.s+r*b.p+j]);return{label:T[b.s+j],vals,varies:new Set(vals).size>1}});
  return{raw,pre:raw.slice(0,b.s),body,post:raw.slice(b.s+b.k*b.p),k:b.k}}

function gen(m){const q=JSON.stringify;
  let o='# Generated by FlowMine\nimport time\n\ndef do(step):\n    print("->", step)  # TODO: replace with real automation\n    time.sleep(0.2)\n\n';
  m.pre.forEach(s=>o+=`do(${q(s)})\n`);
  m.body.forEach((st,j)=>{if(st.varies)o+=`\nVALUES_${j+1} = ${q(st.vals)}`});
  o+=`\n\nfor i in range(${m.k}):\n`;
  m.body.forEach((st,j)=>o+=st.varies?`    do(VALUES_${j+1}[i])\n`:`    do(${q(st.vals[0])})\n`);
  o+='\n';m.post.forEach(s=>o+=`do(${q(s)})\n`);return o}

let model=null,nodes=[],running=false;
const W=520,X=110,NW=300,NH=50,G=34;

function render(m){
  nodes=[...m.pre.map(t=>({t,kind:'pre'})),...m.body.map((b,j)=>({t:b.label,kind:'loop',b,j})),...m.post.map(t=>({t,kind:'post'}))];
  let y=24;nodes.forEach(n=>{n.y=y;y+=NH+G});const H=y-G+24;
  const f=m.pre.length,l=f+m.body.length-1;let s=`<svg viewBox="0 0 ${W} ${H}" width="${W}" role="img" aria-label="Detected workflow"><defs><marker id="ar" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0 0L10 5L0 10z" fill="#68718f"/></marker></defs>`;
  const top=nodes[f].y-18,bot=nodes[l].y+NH+18;
  s+=`<rect class="region" x="94" y="${top}" width="332" height="${bot-top}" rx="14"/>`;
  nodes.forEach((n,i)=>{if(i<nodes.length-1)s+=`<line class="edge" x1="260" y1="${n.y+NH}" x2="260" y2="${nodes[i+1].y}" marker-end="url(#ar)"/>`});
  s+=`<path class="edge" d="M410 ${nodes[l].y+NH/2}H452V${nodes[f].y+NH/2}H414" marker-end="url(#ar)"/>`;
  nodes.forEach((n,i)=>{const t=n.t.length>36?n.t.slice(0,35)+'…':n.t;
    s+=`<g class="node" id="n${i}" tabindex="0" role="button" aria-label="${esc(n.t)}"><rect x="${X}" y="${n.y}" width="${NW}" height="${NH}" rx="9"/><text x="${X+14}" y="${n.y+30}">${esc(t)}</text>${n.b&&n.b.varies?`<circle cx="${X+NW-16}" cy="${n.y+NH/2}" r="5" fill="#f5a300"><title>Changes every run</title></circle>`:''}</g>`});
  s+=`<g class="badge"><rect x="352" y="${top-13}" width="74" height="26" rx="13"/><text id="badge" x="389" y="${top+5}">×${m.k}</text></g></svg>`;
  $('chart').innerHTML=s;
  nodes.forEach((n,i)=>{const e=$('n'+i);e.onclick=()=>pick(i);e.onkeydown=ev=>{if(ev.key==='Enter'||ev.key===' '){ev.preventDefault();pick(i)}}})}

function pick(i){
  document.querySelectorAll('.node').forEach(e=>e.classList.remove('sel'));$('n'+i).classList.add('sel');
  const n=nodes[i];let h='';
  if(n.kind==='loop'){h=`<p>Step in the loop, repeats <b>${model.k} times</b>.</p><p>Pattern: <code>${esc(n.t)}</code></p>`+(n.b.varies?`<p>Changes each run:</p>${n.b.vals.map(v=>`<span class="chip">${esc(v)}</span>`).join('')}`:`<p>Identical every run: <code>${esc(n.b.vals[0])}</code></p>`)}
  else h=`<p>Runs once, ${n.kind==='pre'?'before':'after'} the loop.</p><p><code>${esc(n.t)}</code></p>`;
  $('inspect').innerHTML=h}

function mine(){
  const text=$('log').value.trim();
  if(!text){$('chart').innerHTML='<p class="empty">The log is empty. Paste one action per line, or choose Load sample.</p>';return}
  model=build(text);$('run').disabled=true;$('code').textContent='';$('out').textContent='';
  if(!model.k){$('chart').innerHTML='<p class="empty">No repeated sequence found. FlowMine needs a group of steps that appears at least twice in a row. Add more of the log and try again.</p>';$('stats').textContent='';return}
  render(model);$('run').disabled=false;$('code').textContent=gen(model);
  const steps=nodes.length;$('stats').innerHTML=`<b>${model.raw.length}</b> log lines became <b>${steps}</b> steps.<br>Loop of <b>${model.body.length}</b> steps, repeated <b>${model.k}</b> times.`;
  pick(model.pre.length)}

const sleep=ms=>new Promise(r=>setTimeout(r,ms));
async function run(){
  if(running)return;running=true;$('run').disabled=true;$('out').textContent='';
  document.querySelectorAll('.node').forEach(e=>e.classList.remove('on','done'));
  const m=model,log=s=>{$('out').textContent+=s+'\n';$('out').scrollTop=1e9};
  const hit=(i,s)=>{document.querySelectorAll('.node').forEach(e=>e.classList.remove('on'));$('n'+i).classList.add('on','done');log('-> '+s)};
  let i=0;for(const t of m.pre){hit(i++,t);await sleep(380)}
  const f=i;
  for(let r=0;r<m.k;r++){$('badge').textContent=`${r+1}/${m.k}`;
    if(r>0)document.querySelectorAll('.node').forEach((e,x)=>{if(x>=f&&x<f+m.body.length)e.classList.remove('done')});
    for(let j=0;j<m.body.length;j++){hit(f+j,m.body[j].vals[r]);await sleep(200)}}
  i=f+m.body.length;for(const t of m.post){hit(i++,t);await sleep(380)}
  document.querySelectorAll('.node').forEach(e=>e.classList.remove('on'));
  $('badge').textContent=`×${m.k}`;log('Done.');running=false;$('run').disabled=false}

