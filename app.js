async function play(m,my,parts,badge){
  const alive=()=>my===runId,L=[...$('log-viewer').children];
  // 1. highlight the repeating lines
  for(let r=0;r<m.k;r++)loopIdx(m,r).forEach(i=>L[i].classList.add('hl'));
  await sleep(400);if(!alive())return;
  // 2. repeats 2..k fade out, first run stays
  const fades=[];
  for(let r=1;r<m.k;r++)loopIdx(m,r).forEach(i=>fades.push(fx(L[i],[{opacity:1},{opacity:.22}],{duration:500},{opacity:'0.22'})));
  await Promise.all(fades);if(!alive())return;
  // 3. chart draws in, step by step
  await Promise.all(parts.map((el,i)=>fx(el,[{opacity:0,transform:'translateY(6px)'},{opacity:1,transform:'none'}],{duration:260,delay:i*45},{opacity:'1'})));
  if(!alive())return;
  // 4. badge lands (one bounce), script fades in
  await Promise.all([
    fx(badge,[{opacity:0,transform:'scale(.5)'},{opacity:1,transform:'scale(1.18)',offset:.6},{opacity:1,transform:'scale(1)'}],{duration:300},{opacity:'1'}),
    fx($('code'),[{opacity:0},{opacity:1}],{duration:300},{opacity:'1'})])}

